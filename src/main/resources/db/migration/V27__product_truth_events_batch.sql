CREATE TABLE xianyu_goods_batch_job (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    batch_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(80) NOT NULL,
    operation_type VARCHAR(32) NOT NULL,
    selection_mode VARCHAR(24) NOT NULL,
    selection_query_json LONGTEXT NULL,
    operation_params_json LONGTEXT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    selected_count INT NOT NULL,
    conflict_count INT NOT NULL DEFAULT 0,
    executable_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    unknown_count INT NOT NULL DEFAULT 0,
    max_operations_per_minute INT NOT NULL DEFAULT 10,
    confirmation_summary VARCHAR(1000) NOT NULL,
    operator_user_id BIGINT NULL,
    operator_username VARCHAR(50) NULL,
    started_time DATETIME(3) NULL,
    completed_time DATETIME(3) NULL,
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_goods_batch_id (tenant_id, batch_id),
    UNIQUE KEY uk_goods_batch_request (tenant_id, request_id),
    KEY idx_goods_batch_queue (tenant_id, status, created_time),
    CONSTRAINT fk_goods_batch_operator FOREIGN KEY (operator_user_id) REFERENCES sys_user (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE xianyu_goods_batch_item (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    batch_job_id BIGINT NOT NULL,
    batch_id VARCHAR(64) NOT NULL,
    xianyu_account_id BIGINT NOT NULL,
    xy_goods_id VARCHAR(100) NOT NULL,
    operation_type VARCHAR(32) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    conflict_code VARCHAR(64) NULL,
    conflict_message VARCHAR(1000) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    next_retry_time DATETIME(3) NULL,
    outcome_state VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    platform_response_code VARCHAR(100) NULL,
    result_json LONGTEXT NULL,
    error_message VARCHAR(1000) NULL,
    started_time DATETIME(3) NULL,
    completed_time DATETIME(3) NULL,
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_goods_batch_item (tenant_id, batch_job_id, xianyu_account_id, xy_goods_id),
    KEY idx_goods_batch_item_queue (tenant_id, status, next_retry_time, xianyu_account_id),
    KEY idx_goods_batch_item_goods (tenant_id, xianyu_account_id, xy_goods_id, created_time),
    CONSTRAINT fk_goods_batch_item_job FOREIGN KEY (batch_job_id) REFERENCES xianyu_goods_batch_job (id) ON DELETE CASCADE,
    CONSTRAINT fk_goods_batch_item_account FOREIGN KEY (xianyu_account_id) REFERENCES xianyu_account (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
