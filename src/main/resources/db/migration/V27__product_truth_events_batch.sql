ALTER TABLE xianyu_goods
    ADD COLUMN outer_id VARCHAR(128) NULL AFTER xy_good_id,
    ADD COLUMN product_source VARCHAR(32) NOT NULL DEFAULT 'PLATFORM_LIST_SYNC' AFTER xianyu_account_id,
    ADD COLUMN publish_channel VARCHAR(40) NULL AFTER product_source,
    ADD COLUMN item_type VARCHAR(24) NULL AFTER publish_channel,
    ADD COLUMN category_id VARCHAR(100) NULL AFTER item_type,
    ADD COLUMN category_name VARCHAR(255) NULL AFTER category_id,
    ADD COLUMN business_mode VARCHAR(64) NULL AFTER category_name,
    ADD COLUMN condition_code VARCHAR(64) NULL AFTER business_mode,
    ADD COLUMN original_price DECIMAL(12,2) NULL AFTER sold_price,
    ADD COLUMN shipping_fee DECIMAL(12,2) NULL AFTER original_price,
    ADD COLUMN shipping_type VARCHAR(32) NULL AFTER shipping_fee,
    ADD COLUMN stock INT NULL AFTER sku_count,
    ADD COLUMN sync_status VARCHAR(24) NOT NULL DEFAULT 'PARTIAL' AFTER status,
    ADD COLUMN coverage_status VARCHAR(24) NOT NULL DEFAULT 'PARTIAL' AFTER sync_status,
    ADD COLUMN platform_updated_time DATETIME(3) NULL AFTER coverage_status,
    ADD COLUMN last_synced_time DATETIME(3) NULL AFTER platform_updated_time,
    ADD COLUMN last_sync_request_id VARCHAR(80) NULL AFTER last_synced_time,
    ADD COLUMN platform_snapshot_hash CHAR(64) NULL AFTER last_sync_request_id,
    ADD COLUMN last_sync_error_code VARCHAR(80) NULL AFTER platform_snapshot_hash,
    ADD COLUMN last_sync_error_message VARCHAR(1000) NULL AFTER last_sync_error_code,
    ADD KEY idx_goods_source_channel (tenant_id, product_source, publish_channel),
    ADD KEY idx_goods_outer_id (tenant_id, outer_id),
    ADD KEY idx_goods_sync_state (tenant_id, sync_status, coverage_status, last_synced_time);

UPDATE xianyu_goods
   SET last_synced_time = updated_time,
       platform_updated_time = updated_time
 WHERE last_synced_time IS NULL;

CREATE TABLE xianyu_goods_event (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    xianyu_account_id BIGINT NOT NULL,
    xy_goods_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(48) NOT NULL,
    event_origin VARCHAR(32) NOT NULL,
    outcome_state VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    data_source VARCHAR(32) NOT NULL,
    operator_user_id BIGINT NULL,
    operator_username VARCHAR(50) NULL,
    request_id VARCHAR(80) NULL,
    idempotency_key VARCHAR(100) NULL,
    before_json LONGTEXT NULL,
    after_json LONGTEXT NULL,
    field_diff_json LONGTEXT NULL,
    raw_snapshot_hash CHAR(64) NULL,
    platform_response_code VARCHAR(100) NULL,
    error_message VARCHAR(1000) NULL,
    created_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_goods_event_request (tenant_id, xianyu_account_id, xy_goods_id, event_type, request_id),
    KEY idx_goods_event_timeline (tenant_id, xianyu_account_id, xy_goods_id, created_time),
    KEY idx_goods_event_outcome (tenant_id, outcome_state, created_time),
    CONSTRAINT fk_goods_event_account FOREIGN KEY (xianyu_account_id) REFERENCES xianyu_account (id) ON DELETE CASCADE,
    CONSTRAINT fk_goods_event_operator FOREIGN KEY (operator_user_id) REFERENCES sys_user (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

