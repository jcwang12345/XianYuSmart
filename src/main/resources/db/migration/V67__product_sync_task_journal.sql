-- Task history survives account archival and preserves the exact requested coverage scope.
CREATE TABLE xianyu_product_sync_task (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id BIGINT NOT NULL,
    xianyu_account_id BIGINT NOT NULL,
    request_id VARCHAR(80) NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    scope VARCHAR(24) NOT NULL DEFAULT 'ON_SALE',
    page_size INT NOT NULL,
    max_pages INT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'RUNNING',
    stage VARCHAR(24) NOT NULL DEFAULT 'ACCEPTED',
    coverage VARCHAR(24) NOT NULL DEFAULT 'NONE',
    active_account_id BIGINT NULL,
    worker_token CHAR(36) NULL,
    row_version BIGINT NOT NULL DEFAULT 0,
    pages_requested INT NOT NULL DEFAULT 0,
    pages_completed INT NOT NULL DEFAULT 0,
    discovered_count INT NOT NULL DEFAULT 0,
    saved_count INT NOT NULL DEFAULT 0,
    save_failed_count INT NOT NULL DEFAULT 0,
    detail_success_count INT NOT NULL DEFAULT 0,
    detail_failed_count INT NOT NULL DEFAULT 0,
    reported_total BIGINT NULL,
    progress_json LONGTEXT NULL,
    result_json LONGTEXT NULL,
    last_error_code VARCHAR(64) NULL,
    last_error_message VARCHAR(300) NULL,
    recovery_hint VARCHAR(300) NULL,
    started_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    list_completed_time DATETIME(3) NULL,
    save_completed_time DATETIME(3) NULL,
    detail_completed_time DATETIME(3) NULL,
    updated_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    completed_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_product_sync_request (tenant_id, request_id),
    UNIQUE KEY uk_product_sync_active_account (tenant_id, active_account_id),
    KEY idx_product_sync_account_time (tenant_id, xianyu_account_id, started_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
